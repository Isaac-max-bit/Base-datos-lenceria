-- Este script agrega columnas categoria/color/imagen/precio_anterior
-- a "Producto". El modelo correcto es:
--   categoría → "Producto".tipo_id → "TipoProducto"
--   color     → "VarianteProducto"
-- Se está adaptando a la estructura real de la base.
-- ============================================================
-- PRODUCTOS · Lencería LR
-- Pegar completo en Supabase → SQL Editor → New query → Run.
-- Es idempotente: se puede ejecutar varias veces sin duplicar.
--
-- Tu tabla "Producto" ya tiene una columna obligatoria tipo_id
-- que apunta a "TipoProducto"(id_tipo). Este script crea los
-- tipos que faltan y los asigna a cada producto.
-- ============================================================

-- 1) Tabla base (si ya existe, no hace nada)
create table if not exists "Producto" (
    id_producto bigint generated by default as identity primary key,
    nombre text not null,
    descripcion text,
    precio numeric(10, 2) not null check (precio >= 0),
    stock integer not null default 0 check (stock >= 0),
    fecha_creacion timestamptz not null default now()
);

-- 2) Columnas que usa el frontend (si ya existen, no hace nada)
alter table "Producto" add column if not exists categoria text;
alter table "Producto" add column if not exists color text;
alter table "Producto" add column if not exists imagen text;
alter table "Producto" add column if not exists precio_anterior numeric(10, 2);

-- 3) Tabla de tipos de producto (si ya existe, no hace nada)
create table if not exists "TipoProducto" (
    id_tipo integer generated by default as identity primary key,
    nombre text not null
);

-- 3.1) Crear los 7 tipos si faltan.
--      Se usa id explícito (max + 1) porque la secuencia de la tabla
--      puede estar desincronizada si las filas se insertaron a mano.
--      Al final se repara la secuencia para futuros INSERT.
do $$
declare
    v_nombre      text;
    v_tipo_dato   text;
    v_generacion  text;
    v_siguiente   integer;
    v_secuencia   text;
begin
    select data_type, identity_generation
      into v_tipo_dato, v_generacion
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'TipoProducto'
      and column_name = 'id_tipo';

    if v_tipo_dato is null then
        raise exception 'La tabla "TipoProducto" no tiene la columna id_tipo';
    end if;

    foreach v_nombre in array array[
        'Conjuntos', 'Brasieres', 'Tops', 'Panties',
        'Pijamas', 'Bodies', 'Medias'
    ]
    loop
        if not exists (
            select 1
            from "TipoProducto" t
            where lower(trim(t.nombre)) = lower(v_nombre)
        ) then
            select coalesce(max(id_tipo), 0) + 1
              into v_siguiente
            from "TipoProducto";

            -- GENERATED ALWAYS AS IDENTITY exige OVERRIDING SYSTEM VALUE.
            if v_generacion = 'ALWAYS' then
                insert into "TipoProducto" (id_tipo, nombre)
                overriding system value
                values (v_siguiente, v_nombre);
            else
                insert into "TipoProducto" (id_tipo, nombre)
                values (v_siguiente, v_nombre);
            end if;
        end if;
    end loop;

    -- Reparar la secuencia: el próximo valor será max(id_tipo) + 1.
    v_secuencia := pg_get_serial_sequence('public."TipoProducto"', 'id_tipo');
    if v_secuencia is not null then
        perform setval(
            v_secuencia,
            (select coalesce(max(id_tipo), 0) + 1 from "TipoProducto"),
            false
        );
    end if;
end $$;

-- 4) RLS: lectura pública del catálogo y de los tipos
alter table "Producto" enable row level security;
alter table "TipoProducto" enable row level security;

drop policy if exists "productos_lectura_publica" on "Producto";
create policy "productos_lectura_publica"
    on "Producto"
    for select
    using (true);

drop policy if exists "tipos_lectura_publica" on "TipoProducto";
create policy "tipos_lectura_publica"
    on "TipoProducto"
    for select
    using (true);

